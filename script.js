async function fetchPrayerTimes() {
    const city = document.getElementById('city-select').value;
    const date = new Date();
    const month = date.getMonth() + 1;
    const year = date.getFullYear();
    
    const cacheKey = `prayers_${city}_${month}_${year}`;
    const cachedData = localStorage.getItem(cacheKey);

    // لو في بيانات محفوظة للشهر ده، اعرضها فوراً (عشان لو هو Offline)
    if (cachedData) {
        currentPrayerData = JSON.parse(cachedData);
        updatePrayerUI();
    }

    // لو في إنترنت، جيب أحدث بيانات واحفظها
    if (navigator.onLine) {
        try {
            const res = await fetch(`https://api.aladhan.com/v1/calendarByCity?city=${city}&country=Egypt&method=5&month=${month}&year=${year}`);
            const data = await res.json();
            currentPrayerData = data.data;
            // حفظ البيانات في الموبايل
            localStorage.setItem(cacheKey, JSON.stringify(currentPrayerData));
            updatePrayerUI();
        } catch (error) {
            console.error("Error fetching prayers", error);
        }
    } else if (!cachedData) {
        // لو مفيش نت ومفيش بيانات محفوظة
        document.getElementById('next-prayer-name').innerText = "لا يوجد اتصال";
        showNoInternetModal();
    }
}

function formatTime12(time24) {
    let [hours, minutes] = time24.split(':');
    hours = parseInt(hours);
    const ampm = hours >= 12 ? 'م' : 'ص';
    hours = hours % 12;
    hours = hours ? hours : 12; // 0 becomes 12
    return `${hours}:${minutes} <small>${ampm}</small>`;
}

