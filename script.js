function askFatwaAI() {
    const userInput = document.getElementById('user-input');
    const sendBtn = document.getElementById('send-btn');
    
    if (!userInput) return;

    const rawText = userInput.value.trim();
    if (rawText === '') return;

    // 1. عرض سؤال المستخدم بالعامية الأصيلة كما كتبها (دون تغييرها أمامه)
    addMessage('user', rawText);
    
    // إعداد السؤال وتصحيحه في الخلفية فقط لإرساله إلى السيرفر لضمان دقة الـ AI
    const optimizedQuestion = normalizeUserQuestion(rawText);

    // إفراغ حقل الإدخال وإعادة ضبطه
    userInput.value = '';
    userInput.style.height = 'auto';
    if (sendBtn) sendBtn.disabled = true;

    // 2. إظهار تأثير "جاري التفكير..." النقاط الثلاثة الممتعة
    const typingId = showTypingIndicator();

    // 3. الاتصال الفعلي بالـ Backend (سيرفر البايثون الخاص بك)
    // ملاحظة: استبدل هذا الرابط لاحقاً برابط الـ API أونلاين بعد الرفع (مثل Render)
    const backendURL = "https://nour-alhuda-backend-seven.vercel.app/ask";

    fetch(backendURL, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json'
        },
        body: JSON.stringify({ question: optimizedQuestion }) // إرسال السؤال المُحسّن برمجياً
    })
    .then(response => {
        if (!response.ok) throw new Error("Network response was not ok");
        return response.json();
    })
    .then(data => {
        // إزالة نقاط التحميل وعرض إجابة الذكاء الاصطناعي الحقيقية من السيرفر
        removeTypingIndicator(typingId);
        addMessage('bot', data.answer);
    })
    .catch(error => {
        // إدارة الأخطاء بأمانة واحترافية دون إظهار أكواد معقدة للمستخدم
        removeTypingIndicator(typingId);
        addMessage('bot', "عذراً، واجهنا مشكلة في الاتصال بالمساعد الذكي حالياً. يرجى إعادة إرسال سؤالك الفقهي بعد قليل.");
        console.error("API Error:", error);
    });
}


