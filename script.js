function renderMiniCalendar() {
    const grid = document.getElementById("calendar-grid");
    if (!grid) return;
    grid.innerHTML = "";
    
    let todayObj = new Date();
    let currentYear = todayObj.getFullYear();
    let currentMonth = todayObj.getMonth() + 1;
    // حساب عدد أيام الشهر الحالي تلقائياً
    let daysInMonth = new Date(currentYear, currentMonth, 0).getDate(); 

    for (let i = 1; i <= daysInMonth; i++) {
        let mStr = currentMonth < 10 ? '0' + currentMonth : currentMonth;
        let dStr = i < 10 ? '0' + i : i;
        const dateStr = `${currentYear}-${mStr}-${dStr}`;
        
        const iterDate = new Date(dateStr);
        iterDate.setHours(0,0,0,0);
        const todayComparison = new Date();
        todayComparison.setHours(0,0,0,0);

        const isFuture = iterDate > todayComparison;
        const isDone = localStorage.getItem(`star_${dateStr}`) === 'true';

        const dayDiv = document.createElement("div");
        // إضافة كلاس completed لو اليوم مكتمل عشان النجمة تظهر
        dayDiv.className = `day-num ${dateStr === currentSelectedDate ? 'active-day' : ''} ${isFuture ? 'locked-day' : ''} ${isDone ? 'completed' : ''}`;
        
        // شلنا النجمة من هنا عشان هنحطها بالـ CSS ورا الرقم
        dayDiv.innerHTML = `<span>${i}</span>`;

        if (!isFuture) {
            dayDiv.onclick = () => { currentSelectedDate = dateStr; initTracker(); };
        }
        grid.appendChild(dayDiv);
    }
}


