function compareVersions(v1, v2) {
    const a = String(v1).split('.').map(Number);
    const b = String(v2).split('.').map(Number);
    const len = Math.max(a.length, b.length);
    for (let i = 0; i < len; i++) {
        const x = a[i] || 0;
        const y = b[i] || 0;
        if (x > y) return 1;
        if (x < y) return -1;
    }
    return 0;
}

async function checkForUpdates() {
    const btn = document.getElementById('update-check-btn');
    const statusBox = document.getElementById('update-status');
    if (!btn || !statusBox) return;

    if (!navigator.onLine) {
        statusBox.className = 'update-status error';
        statusBox.innerHTML = '⚠️ يلزم الاتصال بالإنترنت للتحقق من التحديثات';
        return;
    }

    btn.disabled = true;
    btn.classList.add('spinning');
    statusBox.className = 'update-status checking';
    statusBox.innerHTML = 'جاري التحقق...';

    try {
        const res = await fetch(`${REMOTE_VERSION_URL}?t=${Date.now()}`);
        if (!res.ok) throw new Error('bad response');
        const data = await res.json();
        const remoteVersion = data.version;

        if (compareVersions(remoteVersion, APP_VERSION) > 0) {
            statusBox.className = 'update-status available';
            const changelogHTML = Array.isArray(data.changelog) && data.changelog.length
                ? `<ul class="whats-new-list">${data.changelog.map(item => `<li>${escapeHTML(item)}</li>`).join('')}</ul>`
                : '';
            statusBox.innerHTML = `
                🎉 يوجد إصدار جديد v${escapeHTML(remoteVersion)}
                ${changelogHTML}
                <a href="${data.download_url || 'https://linktr.ee/AdhamFares'}" target="_blank" class="update-download-link">
                    <i class="fas fa-download"></i> تحميل التحديث
                </a>`;
        } else {
            statusBox.className = 'update-status up-to-date';
            statusBox.innerHTML = '✅ التطبيق محدث لآخر إصدار';
        }
    } catch (error) {
        console.error('Update check failed:', error);
        statusBox.className = 'update-status error';
        statusBox.innerHTML = '❌ تعذر التحقق من التحديثات، حاول لاحقاً';
    } finally {
        btn.disabled = false;
        btn.classList.remove('spinning');
    }
}

