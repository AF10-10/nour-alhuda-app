const HIJRI_CFG = {
    adjustDays: 0,      // تعديل يدوي بالأيام (+1 أو -1) لو تقويم بلدك يسبق/يتأخر يوماً عن أم القرى
    monthsAhead: 24,    // عدد الشهور الميلادية القادمة التي يخزّنها التطبيق تلقائياً
    cacheKey: 'hijri_cache_v2',
    api: 'https://api.aladhan.com/v1/gToHCalendar'
};
const HIJRI_MONTHS = ["المُحَرَّم", "صَفَر", "ربيع الأول", "ربيع الآخر", "جمادى الأولى", "جمادى الآخرة", "رجب", "شعبان", "رمضان", "شوال", "ذو القعدة", "ذو الحجة"];
const HIJRI_WEEKDAYS = ["الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت"];
let hijriSyncing = false;
let hijriMidnightTimer = null;
let hijriListenersAdded = false;

// ---------- التخزين المحلي ----------
function hijriLoadCache() {
    try {
        const c = JSON.parse(localStorage.getItem(HIJRI_CFG.cacheKey));
        if (c && c.v === 2 && c.months) return c;
    } catch (e) {}
    return { v: 2, months: {} };
}
function hijriSaveCache(c) {
    try { localStorage.setItem(HIJRI_CFG.cacheKey, JSON.stringify(c)); } catch (e) {}
}

// ---------- الحساب المحلي (يعمل بدون إنترنت) ----------
// 1) أم القرى من المتصفح
function hijriFromIntl(date) {
    try {
        const parts = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura-nu-latn', { day: 'numeric', month: 'numeric', year: 'numeric' }).formatToParts(date);
        const o = {};
        parts.forEach(p => { o[p.type] = parseInt(p.value, 10); });
        if (o.year >= 1300 && o.year <= 1800 && o.month >= 1 && o.month <= 12 && o.day >= 1 && o.day <= 30) {
            return { d: o.day, m: o.month, y: o.year };
        }
    } catch (e) {}
    return null;
}
// 2) معادلة رياضية مستقلة تماماً عن المتصفح (آخر حل احتياطي)
function hijriFromTabular(date) {
    const gy = date.getFullYear(), gm = date.getMonth() + 1, gd = date.getDate();
    const a = Math.floor((14 - gm) / 12), yy = gy + 4800 - a, mm = gm + 12 * a - 3;
    const jdn = gd + Math.floor((153 * mm + 2) / 5) + 365 * yy + Math.floor(yy / 4) - Math.floor(yy / 100) + Math.floor(yy / 400) - 32045;
    let l = jdn - 1948440 + 10632;
    const n = Math.floor((l - 1) / 10631);
    l = l - 10631 * n + 354;
    const j = Math.floor((10985 - l) / 5316) * Math.floor((50 * l) / 17719) + Math.floor(l / 5670) * Math.floor((43 * l) / 15238);
    l = l - Math.floor((30 - j) / 15) * Math.floor((17719 * j) / 50) - Math.floor(j / 16) * Math.floor((15238 * j) / 43) + 29;
    const m = Math.floor((24 * l) / 709);
    return { d: l - Math.floor((709 * m) / 24), m: m, y: 30 * n + j - 30 };
}
function hijriApprox(h) { return h.y * 354.3671 + (h.m - 1) * 29.5306 + h.d; }

// ---------- البحث عن تاريخ يوم معيّن: كاش أونلاين ← أم القرى ← معادلة ----------
function hijriLookup(date) {
    const key = date.getFullYear() + '-' + String(date.getMonth() + 1).padStart(2, '0');
    const arr = hijriLoadCache().months[key];
    if (arr && arr[date.getDate() - 1]) {
        const h = arr[date.getDate() - 1];
        return { d: h[0], m: h[1], y: h[2] };
    }
    return hijriFromIntl(date) || hijriFromTabular(date);
}

// ---------- جلب شهر كامل من Aladhan ----------
async function hijriFetchMonth(y, m) {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 10000);
    try {
        const res = await fetch(`${HIJRI_CFG.api}/${m}/${y}`, { signal: ctrl.signal });
        if (!res.ok) throw new Error('HTTP ' + res.status);
        const json = await res.json();
        const days = new Date(y, m, 0).getDate();
        if (json.code !== 200 || !Array.isArray(json.data) || json.data.length !== days) throw new Error('بيانات غير مكتملة');
        return json.data.map((item, i) => {
            const [hd, hm, hy] = item.hijri.date.split('-').map(Number);
            const h = { d: hd, m: hm, y: hy };
            // فحص أمان: لو الفرق عن الحساب المحلي أكبر من 5 أيام نرفض البيانات (خطأ في الـ API)
            const local = hijriFromIntl(new Date(y, m - 1, i + 1, 12)) || hijriFromTabular(new Date(y, m - 1, i + 1, 12));
            if (!(hm >= 1 && hm <= 12 && hd >= 1 && hd <= 30) || Math.abs(hijriApprox(h) - hijriApprox(local)) > 5) throw new Error('بيانات مشبوهة');
            return [hd, hm, hy];
        });
    } finally {
        clearTimeout(timer);
    }
}

// ---------- تجميع الشهور القادمة تلقائياً في الخلفية ----------
async function hijriSyncCache() {
    if (hijriSyncing || !navigator.onLine) return;
    hijriSyncing = true;
    try {
        const cache = hijriLoadCache();
        const now = new Date();
        const keepFrom = new Date(now.getFullYear(), now.getMonth() - 1, 1);
        Object.keys(cache.months).forEach(k => {
            const [ky, km] = k.split('-').map(Number);
            if (new Date(ky, km - 1, 1) < keepFrom) delete cache.months[k];   // حذف الشهور القديمة
        });
        let fails = 0, fetched = 0;
        for (let i = 0; i <= HIJRI_CFG.monthsAhead && fails < 2; i++) {
            const t = new Date(now.getFullYear(), now.getMonth() + i, 1);
            const key = t.getFullYear() + '-' + String(t.getMonth() + 1).padStart(2, '0');
            if (cache.months[key]) continue;
            try {
                cache.months[key] = await hijriFetchMonth(t.getFullYear(), t.getMonth() + 1);
                hijriSaveCache(cache);
                fetched++;
                if (i === 0) hijriRender();                                    // تحديث الشاشة بالبيانات الأونلاين فور وصولها
                await new Promise(r => setTimeout(r, 400));
            } catch (e) {
                fails++;
                console.warn('تعذر جلب شهر هجري:', key, e.message);
            }
        }
        if (fetched) hijriRender();
    } finally {
        hijriSyncing = false;
    }
}

// ---------- عرض التاريخ ----------
function hijriRender() {
    const el = document.getElementById('hijri-date');
    if (!el) return;
    const now = new Date();
    const target = new Date(now.getFullYear(), now.getMonth(), now.getDate() + HIJRI_CFG.adjustDays, 12);
    const h = hijriLookup(target);
    el.innerText = `${HIJRI_WEEKDAYS[now.getDay()]}، ${h.d} ${HIJRI_MONTHS[h.m - 1]} ${h.y} هـ`;
}

function updateFullDate() {
    const now = new Date();

    // التاريخ الميلادي من الجهاز
    const gregorianOptions = { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' };
    const gregorianElement = document.getElementById("gregorian-date");
    if (gregorianElement) gregorianElement.innerText = now.toLocaleDateString('ar-EG', gregorianOptions);

    // الهجري: يظهر فوراً (كاش أو حساب محلي) ثم تبدأ المزامنة في الخلفية
    hijriRender();
    hijriSyncCache();

    // تحديث تلقائي بعد منتصف الليل
    clearTimeout(hijriMidnightTimer);
    const nextMidnight = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 0, 0, 5);
    hijriMidnightTimer = setTimeout(updateFullDate, nextMidnight - now);

    // تحديث عند عودة المستخدم للتطبيق أو رجوع الإنترنت (يُضاف مرة واحدة فقط)
    if (!hijriListenersAdded) {
        hijriListenersAdded = true;
        document.addEventListener('visibilitychange', () => { if (!document.hidden) updateFullDate(); });
        window.addEventListener('online', updateFullDate);
    }
}


