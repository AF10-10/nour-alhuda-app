// 2. دالة التشغيل (بتختار 4 مختلفين كل يوم)
function initChallenges() {
    const container = document.getElementById("challenges-container");
    if(!container) return;
    container.innerHTML = "";
    
    const now = new Date();
    const dateStr = now.toDateString();
    
    // رقم اليوم (مثلاً 32 في السنة) عشان نغير الترتيب
    const dayOfYear = Math.floor((now - new Date(now.getFullYear(), 0, 0)) / 86400000);
    
    // ترتيب عشوائي "ثابت" لليوم ده فقط
    let dailyChallenges = [...allChallenges].sort((a, b) => {
        // بنستخدم ID التحدي مع رقم اليوم لعمل ترتيب مختلف يومياً
        const seedA = (parseInt(a.id.replace('c','')) * dayOfYear) % 7;
        const seedB = (parseInt(b.id.replace('c','')) * dayOfYear) % 7;
        return seedA - seedB;
    }).slice(0, 4); // كدة هيختار 4 من الـ 7

    dailyChallenges.forEach(item => {
        const isDone = localStorage.getItem(item.id + dateStr) === "true";
        const card = document.createElement("div");
        card.className = `challenge-card ${isDone ? 'completed' : ''}`;
        card.innerHTML = `
            <div class="challenge-info">
                <p>${item.title} (${item.goal} مرة)</p>
                <h4>${item.zekr}</h4>
            </div>
            <button class="challenge-btn" onclick="acceptChallenge('${item.id}', ${item.goal}, '${item.zekr}', this)">
                ${isDone ? '<i class="fas fa-check"></i> تم بنجاح' : 'قبول التحدي'}
            </button>
        `;
        container.appendChild(card);
    });
}



