function calculateNextPrayer(todayTimings) {
    if(countdownInterval) clearInterval(countdownInterval);
    
    const prayers = [
        { id: 'Fajr', name: 'الفجر' }, { id: 'Sunrise', name: 'الشروق' },
        { id: 'Dhuhr', name: 'الظهر' }, { id: 'Asr', name: 'العصر' },
        { id: 'Maghrib', name: 'المغرب' }, { id: 'Isha', name: 'العشاء' }
    ];
    
    const now = new Date();
    let nextPrayer = null;
    let nextPrayerDate = null;
    
    for(let i=0; i<prayers.length; i++) {
        const timeStr = todayTimings[prayers[i].id].split(' ')[0];
        const [hours, minutes] = timeStr.split(':');
        let pTime = new Date();
        pTime.setHours(parseInt(hours), parseInt(minutes), 0, 0);
        
        if(pTime > now) {
            nextPrayer = prayers[i];
            nextPrayerDate = pTime;
            break;
        }
    }
    
    // إذا مرت كل الصلوات، القادمة هي الفجر بتاع بكرة
    if(!nextPrayer) {
        nextPrayer = prayers[0];
        const timeStr = todayTimings['Fajr'].split(' ')[0];
        const [hours, minutes] = timeStr.split(':');
        nextPrayerDate = new Date();
        nextPrayerDate.setDate(nextPrayerDate.getDate() + 1); // بكرة
        nextPrayerDate.setHours(parseInt(hours), parseInt(minutes), 0, 0);
    }
    
    // تظليل الصلاة القادمة في المربعات
    document.querySelectorAll('.prayer-time-box').forEach(c => c.classList.remove('active-prayer'));
    const activeCard = document.getElementById(`card-${nextPrayer.id}`);
    if(activeCard) activeCard.classList.add('active-prayer');

    document.getElementById('next-prayer-name').innerText = nextPrayer.name;
    document.getElementById('next-prayer-time').innerHTML = formatTime12(todayTimings[nextPrayer.id].split(' ')[0]);
    
    // تشغيل العداد
    countdownInterval = setInterval(() => {
        const timeDiff = nextPrayerDate - new Date();
        if(timeDiff <= 0) {
            clearInterval(countdownInterval);
            fetchPrayerTimes(); // إعادة حساب اليوم الجديد أو الصلاة الجديدة
            return;
        }
        const h = Math.floor((timeDiff % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
        const m = Math.floor((timeDiff % (1000 * 60 * 60)) / (1000 * 60));
        const s = Math.floor((timeDiff % (1000 * 60)) / 1000);
        document.getElementById('prayer-countdown').innerText = `متبقي: ${h < 10 ? '0'+h : h}:${m < 10 ? '0'+m : m}:${s < 10 ? '0'+s : s}`;
    }, 1000);
}

