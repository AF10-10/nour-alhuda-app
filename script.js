function calculateQibla(lat, lng) {
    const meccaLat = 21.422487 * (Math.PI / 180);
    const meccaLng = 39.826206 * (Math.PI / 180);
    const userLat = lat * (Math.PI / 180);
    const userLng = lng * (Math.PI / 180);

    const y = Math.sin(meccaLng - userLng);
    const x = Math.cos(userLat) * Math.tan(meccaLat) - Math.sin(userLat) * Math.cos(meccaLng - userLng);
    let qibla = Math.atan2(y, x) * (180 / Math.PI);
    return (qibla + 360) % 360;
}

function requestCompassPermission() {
    if (typeof DeviceOrientationEvent !== 'undefined' && typeof DeviceOrientationEvent.requestPermission === 'function') {
        DeviceOrientationEvent.requestPermission()
            .then(permissionState => {
                if (permissionState === 'granted') {
                    startCompassListener();
                } else {
                    alert("نحتاج لصلاحية مستشعر الحركة لتشغيل البوصلة.");
                }
            })
            .catch(console.error);
    } else {
        startCompassListener();
    }
}

function startCompassListener() {
    if ('ondeviceorientationabsolute' in window) {
        window.addEventListener('deviceorientationabsolute', handleOrientation);
    } else {
        window.addEventListener('deviceorientation', handleOrientation);
    }
}

function handleOrientation(event) {
    let compassHeading = 0;
    
    if (event.webkitCompassHeading) {
        compassHeading = event.webkitCompassHeading;
    } else if (event.alpha !== null) {
        compassHeading = 360 - event.alpha;
    }

    if (compassHeading === 0) return;

    // تحديث الرقم المعروض في منتصف البوصلة
    document.getElementById('current-degree').innerText = Math.round(compassHeading);

    let needleAngle = qiblaAngle - compassHeading;
    document.getElementById('kaaba-pointer').style.transform = `rotate(${needleAngle}deg)`;

    // حساب الفرق بين اتجاه المستخدم واتجاه القبلة
    let diff = Math.abs((qiblaAngle - compassHeading + 360) % 360);
    if (diff > 180) diff = 360 - diff;

    const compassCircle = document.getElementById('compass-circle');
    const successMsg = document.getElementById('qibla-success');

    // إذا كان الفرق أقل من 5 درجات، فهذا يعني أن الاتجاه صحيح
    if (diff < 5) {
        compassCircle.classList.add('aligned');
        successMsg.classList.add('show');
    } else {
        compassCircle.classList.remove('aligned');
        successMsg.classList.remove('show');
    }
}


